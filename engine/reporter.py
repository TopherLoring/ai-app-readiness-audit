"""Report generation for readiness findings."""

from __future__ import annotations
import json
from datetime import datetime, timezone
from pathlib import Path
from .checks import Finding, Severity, SEVERITY_ORDER


def render_markdown(findings: list[Finding], meta: dict | None = None) -> str:
    meta = meta or {}
    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    counts = {s.value: 0 for s in Severity}
    for f in findings:
        counts[f.severity.value] += 1

    lines = [
        "# AI-Built Application Readiness Audit Report",
        "",
        f"**Target URL:** {meta.get('base_url', '—')}",
        f"**Generated:** {now}",
        f"**Engine version:** {meta.get('engine_version', '1.0.0')}",
        "",
        "## Summary",
        "",
        "| Severity   | Count |",
        "|------------|-------|",
        f"| Critical   | {counts['critical']} |",
        f"| High       | {counts['high']} |",
        f"| Medium     | {counts['medium']} |",
        f"| Low        | {counts['low']} |",
        f"| Info       | {counts['info']} |",
        f"| **Total**  | **{len(findings)}** |",
        "",
        "> This is a **launch-readiness assessment**, not a comprehensive security audit or penetration test. "
        "It does not guarantee the application is secure.",
        "",
    ]

    if not findings:
        lines += ["No issues detected by the current automated ruleset. Manual review is still recommended before launch.", ""]
        return "\n".join(lines)

    lines += ["## Prioritized Findings", ""]

    for i, f in enumerate(findings, 1):
        lines += [
            f"### {i}. [{f.severity.value.upper()}] {f.title}",
            "",
            f"**Check ID:** `{f.check_id}` · **Effort:** ~{f.effort_minutes} min · **Tags:** {', '.join(f.tags) or '—'}",
            "",
            f.description,
            "",
            "**Evidence**",
            "```",
            f.evidence,
            "```",
            "",
            "**Recommended fix**",
            "",
            f.recommendation,
            "",
            "---",
            "",
        ]

    lines += [
        "## Launch readiness guidance",
        "",
        "1. Resolve all Critical and High findings before inviting real users.",
        "2. Re-run this audit after fixes.",
        "3. Perform a manual walkthrough of primary user journeys.",
        "4. Treat any authentication or secret-handling issues as launch blockers.",
        "",
        "---",
        "*Report generated by AI-Built Application Readiness Audit engine. "
        "Not a substitute for professional security review or formal QA.*",
        "",
    ]
    return "\n".join(lines)


def render_json(findings: list[Finding], meta: dict | None = None) -> str:
    payload = {
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "engine_version": (meta or {}).get("engine_version", "1.0.0"),
        "base_url": (meta or {}).get("base_url"),
        "summary": {s.value: sum(1 for f in findings if f.severity == s) for s in Severity},
        "findings": [f.to_dict() for f in findings],
    }
    return json.dumps(payload, indent=2)


def write_reports(findings: list[Finding], out_dir: str | Path, meta: dict | None = None):
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    md = out / "readiness_audit.md"
    js = out / "readiness_audit.json"
    md.write_text(render_markdown(findings, meta), encoding="utf-8")
    js.write_text(render_json(findings, meta), encoding="utf-8")
    return md, js